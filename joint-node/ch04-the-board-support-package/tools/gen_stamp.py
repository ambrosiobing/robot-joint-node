#!/usr/bin/env python3
"""The build stamp, as a generated translation unit.

    python tools/gen_stamp.py build/stamp.c     # write it
    python tools/gen_stamp.py --print           # just show the line
    python tools/gen_stamp.py --check build/stamp.c

WHY A GENERATED FILE AND NOT `__DATE__`. Those macros are fixed when THEIR OWN
translation unit is compiled, not when the image is linked, so a build whose
only edit is in another file does not recompile the banner and the stamp keeps
the age of whenever that one file last changed. That has produced a false alarm
on this bench three times: a guard that reports a good image as stale is worse
than no guard, because what it throws away is real.

A generated unit is rewritten on every build, so that file always recompiles and
the link is stamped with itself. The cost is that the project never builds as a
no-op, which is the point.

WHY THE BOARD NEEDS THIS AT ALL. The one NUCLEO-H7A3ZI-Q is shared between
volumes, so the image on the part is whatever was flashed last. An application
that names itself catches the obvious case, and it is not enough: on Friday
6 November 2026 a skipped flash step produced a banner identical to the new
image's, character for character, because only the name was in it. The stamp is
what distinguishes two builds of one source; the commit is what distinguishes
two sources.

AND THE DIRTY MARKER IS COMPUTED HERE RATHER THAN TAKEN FROM GIT. `git describe
--dirty` reads tracked modifications against the index and says nothing about an
untracked file, so a build containing a file that is in no history at all reports
a clean hash. Every file in a new chapter starts untracked, which is exactly when
it matters. `git status --porcelain` sees both.
"""
import argparse
import subprocess
import sys
from datetime import datetime
from pathlib import Path

HERE = Path(__file__).resolve().parent.parent
REPO = HERE.parent.parent

WEEKDAYS = ["Monday", "Tuesday", "Wednesday", "Thursday", "Friday",
            "Saturday", "Sunday"]
MONTHS = ["January", "February", "March", "April", "May", "June", "July",
          "August", "September", "October", "November", "December"]


def git(*args):
    """A git command, or None when git has nothing to say."""
    try:
        out = subprocess.run(("git",) + args, cwd=REPO, capture_output=True,
                             text=True, timeout=20)
    except (OSError, subprocess.SubprocessError):
        return None
    if out.returncode != 0:
        return None
    return out.stdout.strip()


def dirty_from_status(status):
    """Why the tree is not clean, or None, from `git status --porcelain`.

    A REASON rather than a boolean, for the usual cause: a boolean certifies
    itself, where a reason has to name something a reader can check.

    SEPARATE FROM THE GIT CALL ON PURPOSE. Untracked files are counted here,
    and that is the whole reason this marker is not `git describe --dirty`,
    which reads tracked modifications against the index and calls a tree with a
    brand new file in it clean. A guard whose failing state cannot be
    constructed in a test is a guard nobody has watched work, so the parsing
    takes a string and test_firstlight.py feeds it the untracked-only case.
    """
    if status is None:
        return "no-git"
    lines = [ln for ln in status.splitlines() if ln.strip()]
    if not lines:
        return None
    tracked = sum(1 for ln in lines if not ln.startswith("??"))
    untracked = sum(1 for ln in lines if ln.startswith("??"))
    parts = []
    if tracked:
        parts.append(f"{tracked} modified")
    if untracked:
        parts.append(f"{untracked} untracked")
    return "+".join(parts)


def dirty_reason():
    return dirty_from_status(git("status", "--porcelain"))


def stamp_line(now=None):
    """The one string the image prints. Field names, not bare values.

    The field names matter: this line has to be unique enough that a capture
    found later can be attributed to the image that produced it, and a row of
    bare numbers is not.
    """
    now = now or datetime.now()
    when = (f"{WEEKDAYS[now.weekday()]} {now.day} {MONTHS[now.month - 1]} "
            f"{now.year}, {now.hour:02d}:{now.minute:02d}:{now.second:02d}")
    commit = git("rev-parse", "--short=12", "HEAD") or "no-commit"
    reason = dirty_reason()
    tree = reason if reason else "clean"
    return f"built {when} from {commit} tree {tree}"


def as_source(line):
    return "\n".join([
        "/* Generated by tools/gen_stamp.py at every build. Do not edit, and do",
        " * not commit: this file lives under build/ because its whole purpose",
        " * is to differ between two builds of the same source. */",
        '#include "stamp.h"',
        "",
        "const char *build_stamp(void)",
        "{",
        f'    return "{line}";',
        "}",
        "",
    ])


def main(argv):
    ap = argparse.ArgumentParser()
    ap.add_argument("out", nargs="?")
    ap.add_argument("--print", action="store_true", dest="show")
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args(argv)

    line = stamp_line()

    if a.show:
        print(line)
        return 0

    if not a.out:
        print("a destination path is required, or --print")
        return 2

    out = Path(a.out)

    if a.check:
        # NOT a comparison against a fresh stamp: two stamps a second apart
        # differ by design, so that would fail always. What is checkable is
        # that the file exists, declares the one function, and carries a line
        # with the fields a reader is told to look for.
        if not out.exists():
            print(f"{out} does not exist, so the image would not link")
            return 1
        have = out.read_text(encoding="utf-8")
        for needed in ("build_stamp", "built ", " from ", " tree "):
            if needed not in have:
                print(f"{out} has no {needed!r}, so the banner cannot say "
                      f"which build it came from")
                return 1
        print(f"stamp present: {out.name}")
        return 0

    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(as_source(line), encoding="utf-8")
    print(f"stamp: {line}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
